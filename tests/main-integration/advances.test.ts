import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { mkdtemp, rm, writeFile, readFile, mkdir } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { InvoiceDatabase } from '../../src/main/db/database'
import { AdvanceService } from '../../src/main/services/advance-service'
import { BackupService, validateBackup, applyPendingRestore } from '../../src/main/services/backup-service'
import { advanceSaveSchema } from '@shared/advances'
import type { Advance } from '@shared/advances'
let root: string, directory: string, db: InvoiceDatabase, service: AdvanceService
const base = { title: '购买材料', amount: 12000, date: '2026-11-01', projectId: null, payee: '材料店', remark: '', invoiceId: null }
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64')
beforeEach(async () => { root = await mkdtemp(join(tmpdir(), 'advance-test-')); directory = join(root, 'data'); db = new InvoiceDatabase(directory); service = new AdvanceService(db, directory) })
afterEach(async () => { db.close(); await rm(root, { recursive: true, force: true }) })
const save = (record: Advance, changes = {}) => service.save({ ...record, ...changes })
describe('垫付记录与收回', () => {
  it('分次收回不抵减支出，拒绝超额收回、倒置日期和过期修改', () => {
    let record = service.save(base)
    const old = record
    record = service.addReturn({ id: record.id, revision: record.revision, amount: 4000, date: '2026-11-02', remark: '第一笔' })
    expect(service.list({})).toMatchObject({ amount: 12000, recovered: 4000, remaining: 8000, unbilledAmount: 12000 })
    expect(() => service.addReturn({ id: record.id, revision: record.revision, amount: 8001, date: '2026-11-02', remark: '' })).toThrow('不能超过')
    expect(() => service.addReturn({ id: record.id, revision: record.revision, amount: 1, date: '2026-10-31', remark: '' })).toThrow('早于')
    expect(() => save(old)).toThrow('已更新')
    expect(() => save(record, { amount: 3999 })).toThrow('不能小于')
    expect(() => save(record, { date: '2026-11-03' })).toThrow('不能晚于')
    record = service.addReturn({ id: record.id, revision: record.revision, amount: 8000, date: '2026-11-03', remark: '' })
    expect(service.list({ status: 'paid' }).total).toBe(1)
    record = service.removeReturn(record.id, record.revision, record.returns[0].id)
    expect(record.remaining).toBe(8000)
    expect(service.list({ status: 'partial' }).total).toBe(1)
    expect(service.list({ status: 'unpaid' }).total).toBe(0)
    service.setDeleted(record.id, record.revision, true)
    expect(service.list({}).total).toBe(0)
    record = service.list({ deleted: true }).items[0]
    expect(record.returns).toHaveLength(1)
    service.setDeleted(record.id, record.revision, false)
    expect(service.list({}).amount).toBe(12000)
  })
  it('同项目、同金额补票不重复计入无票支出，失效关联重新计入', () => {
    const project = db.createProject({ name: '支教团', description: '' })
    const invoice = db.create({ fileName: 'a.pdf', storagePath: 'invoice-files/a.pdf', mimeType: 'application/pdf', fileSize: 100, sha256: 'a'.repeat(64) })
    db.recordOcrSuccess(invoice.id, { rawResponse: {}, normalizedText: '', parsedFields: { totalAmount: 12000, invoiceNumber: '12345678', invoiceDate: '2026-11-01' }, evidence: {}, warnings: [] })
    db.setInvoiceProjects([invoice.id], [project.id])
    let record = service.save({ ...base, projectId: project.id })
    expect(() => save(record, { invoiceId: invoice.id, projectId: null })).toThrow('同一项目')
    expect(() => save(record, { invoiceId: invoice.id, amount: 1 })).toThrow('金额一致')
    record = save(record, { invoiceId: invoice.id })
    expect(service.list({ projectId: project.id })).toMatchObject({ amount: 12000, unbilledAmount: 0, remaining: 12000 })
    expect(() => service.save({ ...base, projectId: project.id, invoiceId: invoice.id })).toThrow('已关联')
    db.batchSetStatus([invoice.id], 'void')
    expect(service.list({ billing: 'unbilled' }).total).toBe(1)
    expect(service.list({}).unbilledAmount).toBe(12000)
    db.batchSetStatus([invoice.id], 'unprocessed')
    expect(service.list({ billing: 'linked' }).total).toBe(1)
    db.softDelete([invoice.id])
    expect(service.list({}).unbilledAmount).toBe(12000)
    expect(service.list({ projectId: null }).total).toBe(0)
    expect(service.list({ keyword: '材料店', dateFrom: '2026-11-01', dateTo: '2026-11-01' }).total).toBe(1)
    db.deleteProject(project.id)
    expect(service.list({ projectId: null }).total).toBe(1)
  })
  it('附件验证、归属检查、备份与恢复一并保留本金及收回明细', async () => {
    const source = join(root, '付款凭证.png'); await writeFile(source, png)
    let record = service.save(base)
    const other = service.save({ ...base, title: '其他' })
    record = await service.addAttachments(record.id, record.revision, [source])
    expect(() => service.attachmentPath(other.id, record.attachments[0].id)).toThrow('不存在')
    expect(await readFile(service.attachmentPath(record.id, record.attachments[0].id))).toEqual(png)
    const invalid = join(root, 'fake.pdf'); await writeFile(invalid, 'this is not a pdf document')
    await expect(service.addAttachments(record.id, record.revision, [source, invalid])).rejects.toThrow('内容有效')
    expect(service.get(record.id).attachments).toHaveLength(1)
    record = service.addReturn({ id: record.id, revision: record.revision, amount: 3000, date: '2026-11-02', remark: '转账' })
    const backup = new BackupService(db, directory)
    const folder = await backup.create(join(root, 'backups'))
    const manifest = await validateBackup(folder)
    expect(manifest.files).toHaveLength(2)
    service.setDeleted(record.id, record.revision, true)
    await backup.prepareRestore(folder)
    db.close(); await applyPendingRestore(directory); db = new InvoiceDatabase(directory); service = new AdvanceService(db, directory)
    expect(service.get(record.id)).toMatchObject({ deleted: false, amount: 12000, recovered: 3000, remaining: 9000 })
    expect(await readFile(service.attachmentPath(record.id, record.attachments[0].id))).toEqual(png)
    record = service.get(record.id)
    record = await service.removeAttachment(record.id, record.revision, record.attachments[0].id)
    expect(record.attachments).toHaveLength(0)
  })
  it('导出完整筛选数据、金额为数值，并校验无效日期和金额', async () => {
    const record = service.save(base)
    service.addReturn({ id: record.id, revision: record.revision, amount: 4567, date: '2026-11-02', remark: '部分' })
    service.save({ ...base, title: '不匹配的记录', date: '2026-10-01' })
    const book = service.workbook({ dateFrom: '2026-11-01' })
    expect(book.worksheets).toHaveLength(3)
    expect(book.getWorksheet('垫付记录')!.rowCount).toBe(2)
    expect(book.getWorksheet('垫付记录')!.getCell('E2').value).toBe(120)
    expect(book.getWorksheet('垫付记录')!.getCell('G2').value).toBe(74.33)
    expect(book.getWorksheet('收回明细')!.getCell('D2').value).toBe(45.67)
    expect(advanceSaveSchema.safeParse({ ...base, date: '2026-02-30' }).success).toBe(false)
    expect(advanceSaveSchema.safeParse({ ...base, amount: -1 }).success).toBe(false)
    expect(advanceSaveSchema.safeParse({ ...base, amount: 0.5 }).success).toBe(false)
  })
})
